"""Tests for the deterministic stale-artifact detector (drift watch).

Two tiers:

* seeded staleness — each surface check is pointed at a minimal fixture
  tree (or a monkeypatched builder) carrying deliberate drift, and must
  report STALE with a regeneration instruction;
* repo-level — the current repository HEAD must be fully FRESH (the tool
  detects only; nothing is regenerated by these tests).
"""

from __future__ import annotations

import hashlib
import json
import subprocess
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

from ruthless_pipeline.certification import stale_artifacts as sa  # noqa: E402


# --- fixture helpers ----------------------------------------------------------


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def _make_schema_tree(root: Path, schemas: dict[str, dict]) -> None:
    for name, payload in schemas.items():
        _write(root / "schemas" / name, json.dumps(payload))


def _inventory_payload(evidence: list[str] | None = None) -> dict:
    return {
        "inventory_id": "fixture",
        "repo": "ninja-ops-guy/adversarial-clothing-pipeline",
        "classes": sorted(sa.INVENTORY_KNOWN_CLASSES),
        "physical_efficacy_claimed": False,
        "scientific_state": {
            "D2-0005": {"armed": False, "ready_to_arm": False}
        },
        "requirements": [
            {
                "id": "1",
                "class": "PARTIAL",
                "evidence": evidence or [],
            }
        ],
    }


# --- schemas -------------------------------------------------------------------


def test_schemas_fresh(tmp_path):
    _make_schema_tree(tmp_path, {"a.schema.json": {"$id": "a"}, "b.schema.json": {"title": "b"}})
    report = sa.check_schemas_registry(tmp_path)
    assert report.status == sa.STATUS_FRESH


def test_schemas_seeded_invalid_json(tmp_path):
    _write(tmp_path / "schemas" / "broken.schema.json", "{not json")
    report = sa.check_schemas_registry(tmp_path)
    assert report.status == sa.STATUS_STALE
    assert any("invalid JSON" in f for f in report.findings)
    assert report.regenerate


