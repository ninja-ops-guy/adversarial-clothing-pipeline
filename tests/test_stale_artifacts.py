# --- manuscript figures / exports -----------------------------------------------


def test_manuscript_pins_fresh(tmp_path):
    source = b"payload"
    _write(tmp_path / "manuscript" / "evidence" / "src.json", "")
    (tmp_path / "manuscript" / "evidence" / "src.json").write_bytes(source)
    digest = hashlib.sha256(source).hexdigest()
    scaffold = {
        "figure_id": "F1",
        "data": [
            {"source_artifacts": {"manuscript/evidence/src.json": digest}}
        ],
    }
    _write(tmp_path / "manuscript" / "figures" / "F1.json", json.dumps(scaffold))
    report = sa._check_manuscript_dir(tmp_path, "manuscript/figures")
    assert report.status == sa.STATUS_FRESH


def test_manuscript_pins_seeded_hash_drift(tmp_path):
    _write(tmp_path / "manuscript" / "evidence" / "src.json", "changed bytes")
    scaffold = {
        "data": [
            {
                "source_artifacts": {
                    "manuscript/evidence/src.json": "0" * 64,
                }
            }
        ]
    }
    _write(tmp_path / "manuscript" / "exports" / "m.json", json.dumps(scaffold))
    report = sa._check_manuscript_dir(tmp_path, "manuscript/exports")
    assert report.status == sa.STATUS_STALE
    assert any("source hash drift" in f for f in report.findings)


def test_manuscript_pins_seeded_missing_source(tmp_path):
    scaffold = {"data": [{"path": "manuscript/evidence/gone.json", "sha256": "0" * 64}]}
    _write(tmp_path / "manuscript" / "figures" / "F1.json", json.dumps(scaffold))
    report = sa._check_manuscript_dir(tmp_path, "manuscript/figures")
    assert report.status == sa.STATUS_STALE
    assert any("is missing" in f for f in report.findings)


# --- cluster results hash pin -----------------------------------------------------


def test_cluster_pin_fresh(tmp_path):
    content = b"frozen simulation output"
    path = tmp_path / sa.CLUSTER_RESULTS_PATH
    path.parent.mkdir(parents=True)
    path.write_bytes(content)
    report = sa.check_cluster_results_pin(
        tmp_path, expected_sha256=hashlib.sha256(content).hexdigest()
    )
    assert report.status == sa.STATUS_FRESH


def test_cluster_pin_seeded_mismatch(tmp_path):
    path = tmp_path / sa.CLUSTER_RESULTS_PATH
    path.parent.mkdir(parents=True)
    path.write_bytes(b"tampered")
    report = sa.check_cluster_results_pin(tmp_path, expected_sha256="0" * 64)
    assert report.status == sa.STATUS_STALE
    assert any("hash pin mismatch" in f for f in report.findings)
    # detect-only: the checker must not rewrite the artifact
    assert path.read_bytes() == b"tampered"


# --- provenance graph / dashboard (builder-level seeding) -------------------------


def test_provenance_graph_seeded_drift(monkeypatch):
    original = sa.build_graph

    def drifted(root):
        graph = original(root)
        graph["nodes"] = graph["nodes"] + [
            {"id": "injected", "path": "injected", "sha256": "0" * 64}
        ]
        return graph

    monkeypatch.setattr(sa, "build_graph", drifted)
    report = sa.check_provenance_graph(REPO_ROOT)
    assert report.status == sa.STATUS_STALE
    assert report.regenerate


def test_dashboard_seeded_drift(monkeypatch):
    from scripts import export_dashboard_data

    original = export_dashboard_data.build_dashboard

    def drifted(root):
        payload = original(root)
        payload["records"].append({"experiment_id": "INJECTED"})
        return payload

    monkeypatch.setattr(export_dashboard_data, "build_dashboard", drifted)
    report = sa.check_dashboard(REPO_ROOT)
    assert report.status == sa.STATUS_STALE
    assert "PYTHONPATH=. python scripts/export_dashboard_data.py" in report.regenerate


# --- report aggregation -----------------------------------------------------------


def test_report_is_machine_readable_and_deterministic():
    report = sa.check_repo(REPO_ROOT)
    payload = report.to_dict()
    assert payload["schema_version"] == "1.0"
    assert payload["generator"] == "scripts/check_stale_artifacts.py"
    surfaces = {s["surface"]: s["status"] for s in payload["surfaces"]}
    assert set(surfaces) == {
        sa.PROVENANCE_GRAPH_PATH,
        sa.SCHEMAS_DIR,
        sa.INVENTORY_PATH,
        sa.MANUSCRIPT_FIGURES_DIR,
        sa.MANUSCRIPT_EXPORTS_DIR,
        sa.DASHBOARD_PATH,
        sa.CLUSTER_RESULTS_PATH,
        "docs/** + manuscript/backlog/**",
    }
    # The documentation surface reuses doc_lint, which has its own dedicated
    # repo-cleanliness test (test_doc_lint.py::test_current_repo_lints_clean);
    # cross-swarm doc drift is reported there. Here we pin the surfaces this
    # tool uniquely owns.
    artifact_surfaces = {
        k: v for k, v in surfaces.items() if k != "docs/** + manuscript/backlog/**"
    }
    assert all(status == sa.STATUS_FRESH for status in artifact_surfaces.values())
    assert payload["stale"] == any(
        status != sa.STATUS_FRESH for status in surfaces.values()
    )


def test_current_repo_artifact_surfaces_fresh_via_cli():
    proc = subprocess.run(
        [sys.executable, "scripts/check_stale_artifacts.py"],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
    )
    payload = json.loads(proc.stdout)
    # Exit code mirrors the aggregate stale flag (0 or 1).
    assert proc.returncode == (1 if payload["stale"] else 0)
    for surface in payload["surfaces"]:
        if surface["surface"] == "docs/** + manuscript/backlog/**":
            continue  # owned by test_doc_lint.py's repo-cleanliness test
        assert surface["status"] == sa.STATUS_FRESH, surface["findings"]


def test_cli_exit_nonzero_on_staleness(tmp_path):
    _write(tmp_path / "schemas" / "broken.schema.json", "{nope")
    proc = subprocess.run(
        [
            sys.executable,
            str(REPO_ROOT / "scripts" / "check_stale_artifacts.py"),
            "--repo-root",
            str(tmp_path),
        ],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
    )
    assert proc.returncode == 1
    payload = json.loads(proc.stdout)
    assert payload["stale"] is True
    statuses = {s["surface"]: s["status"] for s in payload["surfaces"]}
    assert statuses[sa.SCHEMAS_DIR] == sa.STATUS_STALE
